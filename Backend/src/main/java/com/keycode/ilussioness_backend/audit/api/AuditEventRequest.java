package com.keycode.ilussioness_backend.audit.api;

import com.fasterxml.jackson.annotation.JsonAnySetter;
import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import com.keycode.ilussioness_backend.audit.domain.AuditEntityType;
import com.keycode.ilussioness_backend.audit.domain.AuditEventType;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;

import java.util.Map;

/**
 * Frontend audit event payload.
 *
 * <p>Only server-approved event types are accepted (enforced by
 * {@code AuditEventValidator}). The client cannot provide an actor, outcome,
 * source, action or request id: those are derived/generated by the server.</p>
 */
@JsonIgnoreProperties(ignoreUnknown = false)
public record AuditEventRequest(

        @NotNull
        AuditEventType eventType,

        @NotNull
        AuditEntityType entityType,

        @Size(max = 128)
        @Pattern(regexp = "^[A-Za-z0-9._:-]{1,128}$")
        String entityId,

        @Size(max = 10)
        Map<@Size(max = 40) String, Object> metadata
) {

    /**
     * Spring Boot disables Jackson's global fail-on-unknown-properties setting,
     * so the annotation above alone would silently ignore fields such as
     * {@code actorId}. Reject them explicitly for this endpoint.
     */
    @JsonAnySetter
    void rejectUnknownField(String name, Object value) {
        throw new IllegalArgumentException("Unknown audit event field");
    }
}
