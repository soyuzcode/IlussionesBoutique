package com.keycode.ilussioness_backend.audit.service;

import com.keycode.ilussioness_backend.audit.api.AuditEventRequest;
import com.keycode.ilussioness_backend.audit.domain.AuditActorType;
import com.keycode.ilussioness_backend.audit.domain.AuditEntityType;
import com.keycode.ilussioness_backend.audit.domain.AuditEventType;
import com.keycode.ilussioness_backend.audit.domain.AuditLog;
import com.keycode.ilussioness_backend.audit.domain.AuditOutcome;
import com.keycode.ilussioness_backend.audit.domain.AuditSource;
import com.keycode.ilussioness_backend.audit.repository.AuditLogRepository;
import com.keycode.ilussioness_backend.audit.web.RequestIdFilter;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.context.request.RequestAttributes;
import org.springframework.web.context.request.RequestContextHolder;
import org.springframework.web.context.request.ServletRequestAttributes;

import java.time.OffsetDateTime;
import java.time.ZoneOffset;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.UUID;

/**
 * Writes audit events and owns the transaction semantics.
 *
 * <ul>
 *   <li>Frontend events are written in their own transaction
 *       ({@code REQUIRES_NEW}); an audit failure never changes a business
 *       result.</li>
 *   <li>Successful business events use {@code MANDATORY}: they join the
 *       business transaction. If that transaction rolls back, the success
 *       audit is rolled back too. If the audit insert fails, the business
 *       operation fails as well (no success without an audit record).</li>
 *   <li>Failure/rejection events use {@code REQUIRES_NEW} so they survive the
 *       rollback of the failed business transaction.</li>
 * </ul>
 *
 * <p>This service never calls itself and never invokes the HTTP ingestion
 * endpoint, so an audit persistence failure cannot recurse.</p>
 */
@Service
public class AuditService {

    private final AuditLogRepository auditLogRepository;
    private final AuditEventValidator validator;

    public AuditService(AuditLogRepository auditLogRepository, AuditEventValidator validator) {
        this.auditLogRepository = auditLogRepository;
        this.validator = validator;
    }

    @Transactional(propagation = Propagation.REQUIRES_NEW)
    public AuditLog recordClientEvent(AuditEventRequest request) {
        Map<String, Object> metadata = validator.validateClientEvent(request);

        // The browser session id is accepted only as a validated correlation
        // header (see RequestIdFilter), never from the JSON body. Request ids
        // are always generated by the server.
        String sessionId = currentRequestAttribute(RequestIdFilter.SESSION_ID_ATTRIBUTE);

        AuditLog event = build(
                request.eventType(),
                request.entityType(),
                request.entityId(),
                AuditActorType.ANONYMOUS,
                null,
                AuditSource.FRONTEND,
                AuditOutcome.INFO,
                sessionId,
                currentRequestId(),
                metadata
        );

        return auditLogRepository.save(event);
    }

    @Transactional(propagation = Propagation.MANDATORY)
    public AuditLog recordBusinessSuccess(
            AuditEventType eventType,
            AuditEntityType entityType,
            String entityId,
            Map<String, Object> metadata
    ) {
        Map<String, Object> safeMetadata = validator.validateBusinessEvent(eventType, entityType, metadata);

        AuditLog event = build(
                eventType,
                entityType,
                sanitiseBusinessEntityId(entityId),
                AuditActorType.ANONYMOUS,
                null,
                AuditSource.BACKEND,
                AuditOutcome.SUCCESS,
                currentRequestAttribute(RequestIdFilter.SESSION_ID_ATTRIBUTE),
                currentRequestId(),
                safeMetadata
        );

        return auditLogRepository.save(event);
    }

    @Transactional(propagation = Propagation.REQUIRES_NEW)
    public AuditLog recordBusinessFailure(
            AuditEventType eventType,
            AuditEntityType entityType,
            String entityId,
            AuditOutcome outcome,
            Map<String, Object> metadata
    ) {
        if (outcome != AuditOutcome.FAILURE && outcome != AuditOutcome.REJECTED) {
            throw new IllegalArgumentException("Failure audit events require FAILURE or REJECTED outcome");
        }

        Map<String, Object> safeMetadata = validator.validateBusinessEvent(eventType, entityType, metadata);

        AuditLog event = build(
                eventType,
                entityType,
                sanitiseBusinessEntityId(entityId),
                AuditActorType.ANONYMOUS,
                null,
                AuditSource.BACKEND,
                outcome,
                currentRequestAttribute(RequestIdFilter.SESSION_ID_ATTRIBUTE),
                currentRequestId(),
                safeMetadata
        );

        return auditLogRepository.save(event);
    }

    private static AuditLog build(
            AuditEventType eventType,
            AuditEntityType entityType,
            String entityId,
            AuditActorType actorType,
            String actorId,
            AuditSource source,
            AuditOutcome outcome,
            String sessionId,
            String requestId,
            Map<String, Object> metadata
    ) {
        AuditLog event = new AuditLog();
        event.setOccurredAt(OffsetDateTime.now(ZoneOffset.UTC));
        event.setEventType(eventType);
        event.setAction(eventType.getAction());
        event.setActorType(actorType);
        event.setActorId(actorId);
        event.setEntityType(entityType);
        event.setEntityId(entityId);
        event.setEventSource(source);
        event.setOutcome(outcome);
        event.setSessionId(sessionId);
        event.setRequestId(requestId);
        event.setMetadata(metadata == null ? new LinkedHashMap<>() : new LinkedHashMap<>(metadata));
        return event;
    }

    /**
     * Business ids come from existing application data, not from the audit
     * client. Normalise them to a safe identifier shape instead of letting an
     * unusual order id make the business transaction fail during audit
     * validation.
     */
    private static String sanitiseBusinessEntityId(String rawEntityId) {
        if (rawEntityId == null || rawEntityId.isBlank()) {
            return null;
        }
        String cleaned = rawEntityId.trim()
                .replaceAll("[^\\p{L}\\p{N}._:-]", "_");
        if (cleaned.length() > 128) {
            cleaned = cleaned.substring(0, 128);
        }
        return cleaned.isBlank() ? null : cleaned;
    }

    private static String currentRequestId() {
        String requestId = currentRequestAttribute(RequestIdFilter.REQUEST_ID_ATTRIBUTE);
        return requestId == null ? UUID.randomUUID().toString() : requestId;
    }

    private static String currentRequestAttribute(String name) {
        RequestAttributes attributes = RequestContextHolder.getRequestAttributes();
        if (attributes instanceof ServletRequestAttributes servletAttributes) {
            Object value = servletAttributes.getRequest().getAttribute(name);
            if (value instanceof String text && !text.isBlank()) {
                return text;
            }
        }
        return null;
    }
}
